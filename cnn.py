import numpy as np
import matplotlib.pyplot as plt

Kp = 8.0
Ki = 0.4
Kd = 5.0

desired_depth = 5.0
dt = 0.02
simulation_time = 30.0

mass = 1.0
damping = 1.5
max_control = 20.0

depth = 0.0
velocity = 0.0
integral = 0.0
previous_error = desired_depth - depth

time_values = []
depth_values = []
velocity_values = []
error_values = []
control_values = []

for step in range(int(simulation_time / dt)):
    current_time = step * dt

    error = desired_depth - depth
    derivative = (error - previous_error) / dt
    new_integral = integral + error * dt

    raw_control = (
        Kp * error
        + Ki * new_integral
        + Kd * derivative
    )

    control = np.clip(raw_control, -max_control, max_control)

    if (
        abs(raw_control) <= max_control
        or (raw_control > max_control and error < 0)
        or (raw_control < -max_control and error > 0)
    ):
        integral = new_integral

    acceleration = (control - damping * velocity) / mass

    velocity += acceleration * dt
    depth += velocity * dt

    previous_error = error

    time_values.append(current_time)
    depth_values.append(depth)
    velocity_values.append(velocity)
    error_values.append(error)
    control_values.append(control)

time_values = np.array(time_values)
depth_values = np.array(depth_values)
velocity_values = np.array(velocity_values)
error_values = np.array(error_values)
control_values = np.array(control_values)

final_depth = depth_values[-1]
final_error = desired_depth - final_depth
overshoot = max(0.0, np.max(depth_values) - desired_depth)
overshoot_percent = (overshoot / desired_depth) * 100

settling_band = 0.02 * desired_depth
settling_time = None

for i in range(len(depth_values)):
    if np.all(np.abs(depth_values[i:] - desired_depth) <= settling_band):
        settling_time = time_values[i]
        break

print("AUV PID DEPTH CONTROL RESULTS")
print("--------------------------------")
print(f"Desired depth       : {desired_depth:.2f} m")
print(f"Final simulated depth: {final_depth:.3f} m")
print(f"Final depth error   : {final_error:.3f} m")
print(f"Maximum depth       : {np.max(depth_values):.3f} m")
print(f"Overshoot           : {overshoot_percent:.2f}%")
print(f"Final vertical speed: {velocity_values[-1]:.4f} m/s")
print(f"Kp                  : {Kp}")
print(f"Ki                  : {Ki}")
print(f"Kd                  : {Kd}")

if settling_time is not None:
    print(f"Settling time (2%)  : {settling_time:.2f} seconds")
else:
    print("Settling time (2%)  : Not reached during simulation")

plt.figure(figsize=(10, 5))
plt.plot(time_values, depth_values, label="Actual Depth")
plt.axhline(
    y=desired_depth,
    linestyle="--",
    label="Desired Depth"
)
plt.xlabel("Time (seconds)")
plt.ylabel("Depth (metres)")
plt.title("AUV PID Depth Control Response")
plt.legend()
plt.grid(True)
