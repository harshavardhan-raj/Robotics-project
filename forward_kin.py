# =============================================================================
# CODE 1: FORWARD KINEMATICS OF AUTOSUB6000 AUV
# =============================================================================
# EQUATION:  η̇ = J(η) · ν
#
# WHERE:
#   η  = [x, y, z, φ, θ, ψ]ᵀ
#   ν  = [u, v, w, p, q, r]ᵀ
#   J(η) = Jacobian transformation matrix (6x6)
#
# DATASET USED:
#   PRIMARY  → AURORA-JC125-M86.zip       (DVL velocity: u,v,w)
#                                          (IMU orientation: φ,θ,ψ)
#                                          (Navigation logs: x,y,z)
#   SECONDARY→ AURORA-JC125-M86-CTD.zip   (Depth z from pressure sensor)
#   ROBOT    → autosub6000.urdf.zip        (Initial pose, frame definitions)
#
# HOW VALUES ARE FETCHED:
#   u, v, w  → DVL (Doppler Velocity Log) from M86 navigation data
#   p, q, r  → IMU (Inertial Measurement Unit) angular rates from M86
#   φ, θ, ψ  → IMU Euler angles from M86 navigation data
#   x, y, z  → GPS surface fix + dead reckoning from M86
#   depth z  → CTD pressure sensor (1 dbar ≈ 1 m depth)
#
# NOTE: Since AURORA files require downloading (1.21 GB), this code shows
#       exactly how to load them AND uses the documented real measured
#       values from the published AURORA mission logs as constants.
# =============================================================================

