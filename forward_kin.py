def rotation_matrix_R(phi, theta, psi):
    """
    J1(η) — Rotation Matrix R
    Transforms body-frame LINEAR velocities → world-frame velocities

    R = Rz(ψ) · Ry(θ) · Rx(φ)

    Source: Fossen (2011) "Handbook of Marine Craft Hydrodynamics and Motion Control"
    Used in: Autosub6000 navigation computer onboard software
    """
    cphi   = np.cos(phi);   sphi   = np.sin(phi)
    ctheta = np.cos(theta); stheta = np.sin(theta)
    cpsi   = np.cos(psi);   spsi   = np.sin(psi)

    R = np.array([
        [cpsi*ctheta,
         cpsi*stheta*sphi - spsi*cphi,
         cpsi*stheta*cphi + spsi*sphi],

        [spsi*ctheta,
         spsi*stheta*sphi + cpsi*cphi,
         spsi*stheta*cphi - cpsi*sphi],

        [-stheta,
         ctheta*sphi,
         ctheta*cphi]
    ])
    return R

def angular_velocity_transform_J2(phi, theta):
    """
    J2(η) — Angular Velocity Transformation
    Transforms body-frame ANGULAR rates → world-frame Euler angle rates

    Warning: Singular when θ = ±90° (gimbal lock)
    Autosub6000 pitch stays within ±30° in normal ops — safe range
    """
    cphi   = np.cos(phi);   sphi   = np.sin(phi)
    ctheta = np.cos(theta); ttheta = np.tan(theta)

    # Avoid division by zero (gimbal lock protection)
    if abs(ctheta) < 1e-6:
        ctheta = 1e-6

    J2 = np.array([
        [1,  sphi*ttheta,  cphi*ttheta],
        [0,  cphi,        -sphi       ],
        [0,  sphi/ctheta,  cphi/ctheta]
    ])
    return J2

def jacobian_J(phi, theta, psi):
    """
    Full 6x6 Jacobian Matrix J(η)

    J(η) = | R(η)   0    |
           |  0    J2(η) |

    Maps: ν (body frame) → η̇ (world frame)
    """
    R  = rotation_matrix_R(phi, theta, psi)
    J2 = angular_velocity_transform_J2(phi, theta)

    J = np.zeros((6, 6))
    J[0:3, 0:3] = R    # upper-left: linear velocity transform
    J[3:6, 3:6] = J2   # lower-right: angular velocity transform
    return J

def forward_kinematics(eta, nu):
    """
    FORWARD KINEMATICS:  η̇ = J(η) · ν

    Inputs:
        eta : [x, y, z, φ, θ, ψ] — current pose (world frame)
        nu  : [u, v, w, p, q, r] — body velocities (body frame)

    Output:
        eta_dot : [ẋ, ẏ, ż, φ̇, θ̇, ψ̇] — rate of change of pose
    """
    phi, theta, psi = eta[3], eta[4], eta[5]
    J   = jacobian_J(phi, theta, psi)
    eta_dot = J @ nu   # Matrix multiplication: J(η) · ν
    return eta_dot, J

