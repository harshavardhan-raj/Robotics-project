# Initial state from AURORA dataset
eta = np.array([x0, y0, z0,
                IMU_roll_phi, IMU_pitch_theta, IMU_yaw_psi])

# Body velocities from AURORA DVL + IMU
nu  = np.array([DVL_surge_u, DVL_sway_v, DVL_heave_w,
                IMU_roll_rate_p, IMU_pitch_rate_q, IMU_yaw_rate_r])

# Simulation parameters
dt         = 0.5    # s — time step (AURORA nav logs at 2 Hz)
T_total    = 60.0   # s — 60 seconds of mission
time_steps = np.arange(0, T_total + dt, dt)

# Storage arrays
history_eta     = []
history_eta_dot = []
history_J_norm  = []

print(f"\n{'='*65}")
print(f"  FORWARD KINEMATICS — TIME STEP RESULTS")
print(f"  η̇ = J(η) · ν")
print(f"{'='*65}")
print(f"{'Time':>6} {'x(m)':>8} {'y(m)':>8} {'z(m)':>8} "
      f"{'φ(°)':>7} {'θ(°)':>7} {'ψ(°)':>7} "
      f"{'ẋ':>7} {'ẏ':>7} {'ż':>7}")
print("-" * 85)

for i, t in enumerate(time_steps):
    # APPLY FORWARD KINEMATICS EQUATION
    eta_dot, J = forward_kinematics(eta, nu)

    # Store results
    history_eta.append(eta.copy())
    history_eta_dot.append(eta_dot.copy())
    history_J_norm.append(np.linalg.norm(J))

    # Print every 5 steps
    if i % 5 == 0:
        print(f"{t:6.1f} "
              f"{eta[0]:8.3f} {eta[1]:8.3f} {eta[2]:8.3f} "
              f"{np.degrees(eta[3]):7.2f} {np.degrees(eta[4]):7.2f} "
              f"{np.degrees(eta[5]):7.2f} "
              f"{eta_dot[0]:7.4f} {eta_dot[1]:7.4f} {eta_dot[2]:7.4f}")

    # Integrate: η(t+dt) = η(t) + η̇(t)·dt  [Euler integration]
    eta = eta + eta_dot * dt

    # Keep depth realistic (bounded by seabed depth from AURORA multibeam)
    eta[2] = np.clip(eta[2], 0, 200)

# Convert to numpy arrays
history_eta     = np.array(history_eta)
history_eta_dot = np.array(history_eta_dot)

