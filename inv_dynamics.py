print(f"\n{'='*65}")
print(f"  INVERSE DYNAMICS — TIME STEP RESULTS")
print(f"  τ = M·ν̇d + C(ν)·ν + D(ν)·ν + g(η)")
print(f"{'='*65}")
print(f"{'Time':>6} {'u':>7} {'τ_X(N)':>9} {'τ_Y(N)':>9} "
      f"{'τ_N(Nm)':>9} {'T(J)':>10} {'U(J)':>10} {'WP':>4}")
print("-" * 80)

for i, t in enumerate(time_steps):
    if current_wp >= len(WAYPOINTS):
        break

    wp = WAYPOINTS[current_wp]

    # Guidance: compute ν_d, ν̇_d from waypoint
    nu_d, nu_dot_d, dist = guidance(eta, nu, wp, prev_nu, dt)

    # Build matrices at current state
    C  = build_C(nu)
    D  = build_D(nu)
    g  = build_g(eta)

    # =====================================================
    # INVERSE DYNAMICS EQUATION:
    # τ = M·ν̇desired + C(ν)·ν + D(ν)·ν + g(η)
    # =====================================================
    M_nu_dot = M_matrix @ nu_dot_d
    C_nu     = C @ nu
    D_nu     = D @ nu

    tau = M_nu_dot + C_nu + D_nu + g

    # Saturate to thruster limits (autosub6000.urdf)
    tau = np.clip(tau, TAU_MIN, TAU_MAX)

    # Energies
    T_e = 0.5 * nu @ M_matrix @ nu
    U_e = W * (zg + eta[2]) - B * (zb + eta[2])
    E_e = T_e + U_e

    # Store
    hist_tau.append(tau.copy())
    hist_nu.append(nu.copy())
    hist_nu_d.append(nu_d.copy())
    hist_Mnu_dot.append(M_nu_dot.copy())
    hist_Cnu.append(C_nu.copy())
    hist_Dnu.append(D_nu.copy())
    hist_g.append(g.copy())
    hist_T.append(T_e)
    hist_U.append(U_e)
    hist_E.append(E_e)
    hist_eta.append(eta.copy())

    if i % 4 == 0:
        print(f"{t:6.1f} "
              f"{nu[0]:7.4f} "
              f"{tau[0]:9.2f} {tau[1]:9.2f} "
              f"{tau[5]:9.2f} "
              f"{T_e:10.2f} {U_e:10.2f} {current_wp:>4}")

    # Integrate using nu_d (desired velocity drives motion)
    prev_nu = nu.copy()
    nu += (nu_d - nu) * 0.3 * dt   # first-order lag toward desired

    # Update position
    phi, theta, psi = eta[3], eta[4], eta[5]
    cp = np.cos(phi); sp = np.sin(phi)
    ct = np.cos(theta); st = np.sin(theta)
    cpsi = np.cos(psi); spsi = np.sin(psi)
    R = np.array([
        [cpsi*ct, cpsi*st*sp-spsi*cp, cpsi*st*cp+spsi*sp],
        [spsi*ct, spsi*st*sp+cpsi*cp, spsi*st*cp-cpsi*sp],
        [-st,     ct*sp,              ct*cp              ]
    ])
    eta[0:3] += R @ nu[0:3] * dt
    eta[3]   += nu[3] * dt
    eta[4]   += nu[4] * dt
    eta[5]   += nu[5] * dt
    eta[2]    = np.clip(eta[2], 0, 500)

    if dist < ARRIVAL:
        print(f"\n  ✅ WP{current_wp} reached at t={t:.1f}s | "
              f"τ_X={tau[0]:.1f}N τ_Y={tau[1]:.1f}N τ_N={tau[5]:.1f}N·m")
        current_wp += 1

# Convert
