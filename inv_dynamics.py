M_matrix = build_M()

# Initial state (AURORA M86 mission start)
eta = np.array([WAYPOINTS[0,0], WAYPOINTS[0,1], WAYPOINTS[0,2],
                np.radians(1.2), np.radians(-2.5), np.radians(47.0)])
nu  = np.zeros(6)
prev_nu = nu.copy()

dt        = 0.5
T_total   = 120.0
time_steps = np.arange(0, T_total + dt, dt)

current_wp = 1
ARRIVAL    = 3.0

