# =============================================================================
# CODE 4: INVERSE DYNAMICS OF AUTOSUB6000 AUV
# =============================================================================
# EQUATION:  τ = M·ν̇desired + C(ν)·ν + D(ν)·ν + g(η)
#
# WHERE:
#   τ           = [X, Y, Z, K, M, N]ᵀ → required thruster forces & moments
#   M·ν̇desired  = inertial term (desired acceleration × mass)
#   C(ν)·ν      = Coriolis & centripetal compensation
#   D(ν)·ν      = damping compensation (drag feedforward)
#   g(η)        = gravity & buoyancy compensation
#
# DATASET USED:
#   PRIMARY  → AURORA-JC125-M86.zip       (desired trajectory waypoints, IMU)
#                                          (DVL velocity for C, D computation)
#   SECONDARY→ AURORA-JC125-M86-CTD.zip   (ρ for buoyancy in g(η))
#   ROBOT    → autosub6000.urdf.zip        (M matrix, thruster limits, geometry)
#
# HOW VALUES ARE FETCHED:
#   ν (current)     → DVL + IMU from M86 navigation data
#   ν̇ (desired)     → differentiated from waypoint sequence (M86 nav logs)
#   M               → URDF inertia + computed added mass
#   C, D, g terms   → computed from current state ν and η
#   τ limits        → URDF thruster saturation: ±350 N per thruster
# =============================================================================

