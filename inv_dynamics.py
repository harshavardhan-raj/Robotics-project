# ---- From autosub6000.urdf ----
m    = 2800.0  # kg
Ix   =   85.0  # kg·m²
Iy   =  980.0  # kg·m²
Iz   =  980.0  # kg·m²
Ixy = Ixz = Iyz = 0.0
xg, yg, zg = 0.0, 0.0, 0.02   # m — center of gravity
xb, yb, zb = 0.0, 0.0, 0.0    # m — center of buoyancy

# ---- Volume (from URDF collision geometry) ----
V = np.pi * 0.35**2 * 5.5   # = 2.117 m³

# ---- Added Mass (NOC hydrodynamic report) ----
Xu_dot = -280.0; Yv_dot = -640.0; Zw_dot = -640.0
Kp_dot =  -10.0; Mq_dot = -290.0; Nr_dot = -290.0

# ---- Damping ----
Xu =  -70.0; Yv = -200.0; Zw = -200.0
Kp =  -20.0; Mq = -100.0; Nr = -100.0
Xuu = -320.0; Yvv = -900.0; Zww = -900.0
Kpp =  -50.0; Mqq = -350.0; Nrr = -350.0

# ---- CTD water density (from AURORA M86 CTD) ----
CTD_temperature_C = 8.4
CTD_salinity_ppt  = 34.9
