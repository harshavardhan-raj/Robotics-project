def build_M():
    M_RB = np.array([
        [m,    0,    0,    0,      m*zg,  -m*yg ],
        [0,    m,    0,   -m*zg,   0,      m*xg ],
        [0,    0,    m,    m*yg,  -m*xg,   0    ],
        [0,   -m*zg, m*yg, Ix,   -Ixy,   -Ixz  ],
        [m*zg, 0,   -m*xg,-Ixy,   Iy,    -Iyz  ],
        [-m*yg, m*xg, 0,  -Ixz,  -Iyz,    Iz   ]
    ])
    M_A = -np.diag([Xu_dot, Yv_dot, Zw_dot, Kp_dot, Mq_dot, Nr_dot])
    return M_RB + M_A

def build_C(nu):
    u, v, w, p, q, r = nu
    C_RB = np.array([
        [0,   0,   0,   m*(yg*q + zg*r), -m*(xg*q - w),   -m*(xg*r + v)],
        [0,   0,   0,  -m*(yg*p + w),     m*(zg*r + xg*p), -m*(yg*r - u)],
        [0,   0,   0,  -m*(zg*p - v),    -m*(zg*q + u),     m*(xg*p + yg*q)],
        [-m*(yg*q+zg*r), m*(yg*p+w),  m*(zg*p-v),  0, Iyz*q+Ixz*p-Iz*r, -Iyz*r-Ixy*p+Iy*q],
        [m*(xg*q-w), -m*(zg*r+xg*p),  m*(zg*q+u), -(Iyz*q+Ixz*p-Iz*r), 0, Ixz*r+Ixy*q-Ix*p],
        [m*(xg*r+v), m*(yg*r-u), -m*(xg*p+yg*q), Iyz*r+Ixy*p-Iy*q, -(Ixz*r+Ixy*q-Ix*p), 0]
    ])
    C_A = np.array([
        [0,   0,   0,   0,         -Zw_dot*w,   Yv_dot*v],
        [0,   0,   0,   Zw_dot*w,   0,          -Xu_dot*u],
        [0,   0,   0,  -Yv_dot*v,   Xu_dot*u,   0        ],
        [0,  -Zw_dot*w, Yv_dot*v,  0,          -Nr_dot*r,  Mq_dot*q],
        [Zw_dot*w, 0,  -Xu_dot*u,  Nr_dot*r,   0,          -Kp_dot*p],
        [-Yv_dot*v, Xu_dot*u, 0,  -Mq_dot*q,   Kp_dot*p,   0        ]
    ])
    return C_RB + C_A

def build_D(nu):
    u, v, w, p, q, r = nu
    D_l  = -np.diag([Xu, Yv, Zw, Kp, Mq, Nr])
    D_nl = -np.diag([Xuu*abs(u), Yvv*abs(v), Zww*abs(w),
                     Kpp*abs(p), Mqq*abs(q), Nrr*abs(r)])
    return D_l + D_nl

def build_g(eta):
    phi, theta, psi = eta[3], eta[4], eta[5]
    cphi   = np.cos(phi);  sphi   = np.sin(phi)
    ctheta = np.cos(theta); stheta = np.sin(theta)
    return np.array([
        (W - B) * stheta,
        -(W - B) * ctheta * sphi,
        -(W - B) * ctheta * cphi,
        -(yg*W - yb*B)*ctheta*cphi + (zg*W - zb*B)*ctheta*sphi,
         (zg*W - zb*B)*stheta + (xg*W - xb*B)*ctheta*cphi,
        -(xg*W - xb*B)*ctheta*sphi - (yg*W - yb*B)*stheta
    ])

# =============================================================================
# SECTION 4: GUIDANCE — Compute desired ν and ν̇ from waypoints
# Source: AURORA M86 nav waypoints differentiated for acceleration
# =============================================================================

def guidance(eta, nu, waypoint, prev_nu, dt):
    """
    Compute desired body-frame velocity ν_d and acceleration ν̇_d
    from current state and next waypoint

    Based on Autosub6000 Line-of-Sight (LOS) guidance law
    Used in M86 mission autonomous guidance module
    """
    # Position error in world frame
    pos_error = waypoint - eta[0:3]
    dist      = np.linalg.norm(pos_error)

    Kp_gain = 0.15   # proportional gain
    speed   = np.clip(Kp_gain * dist, 0, CRUISE_SPEED)

    # Desired world-frame velocity
    if dist > 0.01:
        direction = pos_error / dist
    else:
        direction = np.zeros(3)

    # Convert to body frame (using Jacobian inverse)
    phi, theta, psi = eta[3], eta[4], eta[5]
    cp = np.cos(phi); sp = np.sin(phi)
    ct = np.cos(theta); st = np.sin(theta)
    cpsi = np.cos(psi); spsi = np.sin(psi)

    # Rᵀ (inverse of rotation)
    Rt = np.array([
        [cpsi*ct,   spsi*ct,   -st  ],
        [cpsi*st*sp-spsi*cp, spsi*st*sp+cpsi*cp, ct*sp],
        [cpsi*st*cp+spsi*sp, spsi*st*cp-cpsi*sp, ct*cp]
    ])

    nu_d       = np.zeros(6)
    nu_d[0:3]  = Rt @ (direction * speed)
    nu_d[0]    = np.clip(nu_d[0], -CRUISE_SPEED, CRUISE_SPEED)
    nu_d[1]    = np.clip(nu_d[1], -0.5, 0.5)
    nu_d[2]    = np.clip(nu_d[2], -0.3, 0.3)

    # Yaw toward waypoint
    desired_psi = np.arctan2(pos_error[1], pos_error[0])
    yaw_error   = desired_psi - eta[5]
    yaw_error   = np.arctan2(np.sin(yaw_error), np.cos(yaw_error))
    nu_d[5]     = np.clip(0.5 * yaw_error, -0.3, 0.3)

    # Desired acceleration = finite difference
    nu_dot_d    = (nu_d - prev_nu) / dt if dt > 0 else np.zeros(6)

    return nu_d, nu_dot_d, dist

