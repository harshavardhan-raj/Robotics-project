def build_M():
    """
    M = M_RB + M_A
    Rigid-body inertia + hydrodynamic added mass
    Source: autosub6000.urdf + NOC hydrodynamic report
    """
    # Rigid body inertia M_RB (6x6)
    M_RB = np.array([
        [m,    0,    0,    0,      m*zg,  -m*yg ],
        [0,    m,    0,   -m*zg,   0,      m*xg ],
        [0,    0,    m,    m*yg,  -m*xg,   0    ],
        [0,   -m*zg, m*yg, Ix,   -Ixy,   -Ixz  ],
        [m*zg, 0,   -m*xg,-Ixy,   Iy,    -Iyz  ],
        [-m*yg, m*xg, 0,  -Ixz,  -Iyz,    Iz   ]
    ])
    # Added mass M_A (diagonal — standard for slender body Autosub6000)
    M_A = -np.diag([Xu_dot, Yv_dot, Zw_dot, Kp_dot, Mq_dot, Nr_dot])

    return M_RB + M_A

def build_C(nu):
    """
    C(ν) = C_RB(ν) + C_A(ν)
    Coriolis & centripetal matrix
    Appears during turning — couples surge, sway, yaw
    """
    u, v, w, p, q, r = nu

    # Rigid-body Coriolis (simplified for diagonal inertia, xg=yg=0, zg small)
    C_RB = np.array([
        [0,   0,   0,   m*(yg*q + zg*r), -m*(xg*q - w),   -m*(xg*r + v)],
        [0,   0,   0,  -m*(yg*p + w),     m*(zg*r + xg*p), -m*(yg*r - u)],
        [0,   0,   0,  -m*(zg*p - v),    -m*(zg*q + u),     m*(xg*p + yg*q)],
        [-m*(yg*q+zg*r), m*(yg*p+w),  m*(zg*p-v),  0,       Iyz*q+Ixz*p-Iz*r, -Iyz*r-Ixy*p+Iy*q],
        [m*(xg*q-w),    -m*(zg*r+xg*p),  m*(zg*q+u), -(Iyz*q+Ixz*p-Iz*r), 0, Ixz*r+Ixy*q-Ix*p],
        [m*(xg*r+v),    m*(yg*r-u),  -m*(xg*p+yg*q), Iyz*r+Ixy*p-Iy*q, -(Ixz*r+Ixy*q-Ix*p), 0]
    ])

    # Added mass Coriolis (diagonal M_A assumption)
    C_A = np.array([
        [0,   0,   0,   0,         -Zw_dot*w,   Yv_dot*v],
        [0,   0,   0,   Zw_dot*w,   0,          -Xu_dot*u],
        [0,   0,   0,  -Yv_dot*v,   Xu_dot*u,   0        ],
        [0,  -Zw_dot*w, Yv_dot*v,   0,          -Nr_dot*r,  Mq_dot*q],
        [Zw_dot*w, 0,  -Xu_dot*u,   Nr_dot*r,   0,          -Kp_dot*p],
        [-Yv_dot*v, Xu_dot*u, 0,   -Mq_dot*q,   Kp_dot*p,   0        ]
    ])

    return C_RB + C_A

def build_D(nu):
    """
    D(ν) = D_linear + D_nonlinear(ν)
    Hydrodynamic damping — drag forces
    Linear: skin friction | Quadratic: pressure drag
    """
    u, v, w, p, q, r = nu

    D_linear = -np.diag([Xu, Yv, Zw, Kp, Mq, Nr])

    D_nonlinear = -np.diag([
        Xuu * abs(u),
        Yvv * abs(v),
        Zww * abs(w),
        Kpp * abs(p),
        Mqq * abs(q),
        Nrr * abs(r)
    ])

    return D_linear + D_nonlinear

def build_g(eta):
    """
    g(η) — Restoring forces and moments
    Gravity (W) vs Buoyancy (B) — depth-dependent

    g(η) = [(W-B)sinθ, -(W-B)cosθsinφ, -(W-B)cosθcosφ,
             -(yg·W - yb·B)cosθcosφ + (zg·W - zb·B)cosθsinφ,
              (zg·W - zb·B)sinθ + (xg·W - xb·B)cosθcosφ,
             -(xg·W - xb·B)cosθsinφ - (yg·W - yb·B)sinθ]
    """
    phi, theta, psi = eta[3], eta[4], eta[5]
    cphi = np.cos(phi); sphi = np.sin(phi)
    ctheta = np.cos(theta); stheta = np.sin(theta)

    g_vec = np.array([
        (W - B) * stheta,
        -(W - B) * ctheta * sphi,
        -(W - B) * ctheta * cphi,
        -(yg*W - yb*B)*ctheta*cphi + (zg*W - zb*B)*ctheta*sphi,
         (zg*W - zb*B)*stheta + (xg*W - xb*B)*ctheta*cphi,
        -(xg*W - xb*B)*ctheta*sphi - (yg*W - yb*B)*stheta
    ])
    return g_vec

