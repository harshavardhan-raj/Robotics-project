for i, t in enumerate(time_steps):
    # Get thruster force (from AURORA M86 mission profile)
    tau = get_thrust(t, T_total)

    # Build dynamic matrices at current state
    C  = build_C(nu)
    D  = build_D(nu)
    g  = build_g(eta)

    # =====================================================
    # FORWARD DYNAMICS EQUATION:
    # ν̇ = M⁻¹ [τ - C(ν)ν - D(ν)ν - g(η)]
    # =====================================================
    nu_dot = M_inv @ (tau - C @ nu - D @ nu - g)

    # Compute energies at this step
    T_energy = kinetic_energy(nu, M_matrix)
    U_energy = potential_energy(eta)
    E_total  = T_energy + U_energy

    # Store
    hist_nu.append(nu.copy())
    hist_nu_dot.append(nu_dot.copy())
    hist_T.append(T_energy)
    hist_U.append(U_energy)
    hist_E.append(E_total)
    hist_tau.append(tau.copy())
    hist_Cnu.append((C @ nu).copy())
    hist_Dnu.append((D @ nu).copy())
    hist_g.append(g.copy())

    # Print every 5 steps
    if i % 5 == 0:
        print(f"{t:6.1f} "
              f"{nu[0]:8.4f} {nu[1]:8.4f} {nu[2]:8.4f} "
              f"{tau[0]:8.2f} "
              f"{T_energy:10.2f} {U_energy:10.2f} {E_total:10.2f}")

    # Euler integration: ν(t+dt) = ν(t) + ν̇(t)·dt
    nu  = nu  + nu_dot * dt

    # FK to update position
    from numpy import cos, sin, tan
    phi, theta, psi = eta[3], eta[4], eta[5]
    R = np.array([
        [cos(psi)*cos(theta), cos(psi)*sin(theta)*sin(phi)-sin(psi)*cos(phi), cos(psi)*sin(theta)*cos(phi)+sin(psi)*sin(phi)],
        [sin(psi)*cos(theta), sin(psi)*sin(theta)*sin(phi)+cos(psi)*cos(phi), sin(psi)*sin(theta)*cos(phi)-cos(psi)*sin(phi)],
        [-sin(theta),         cos(theta)*sin(phi),                            cos(theta)*cos(phi)]
    ])
    eta[0:3] += R @ nu[0:3] * dt
    eta[3]   += nu[3] * dt
    eta[4]   += nu[4] * dt
    eta[5]   += nu[5] * dt
    eta[2]    = np.clip(eta[2], 0, 500)

