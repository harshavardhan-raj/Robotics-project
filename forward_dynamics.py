def get_thrust(t, T_total):
    """
    Thruster force profile estimated from AURORA M86 mission logs
    Source: nav/acceleration_estimate.csv from M86 navigation data

    Mission phases observed in M86:
      0–10s   : Acceleration from rest (full thrust)
      10–50s  : Cruise (reduced thrust, balancing drag)
      50–55s  : Obstacle avoidance turn (sway + yaw added)
      55–60s  : Resume cruise
    """
    tau = np.zeros(6)

    if t < 10.0:
        # Phase 1: Acceleration — M86 log shows ~150N during start
        tau[0] = 150.0        # surge force X (N)
        tau[2] = (W - B)      # heave: compensate buoyancy

    elif t < 50.0:
        # Phase 2: Cruise — M86 log: ~70N to maintain 1.35 m/s vs drag
        tau[0] = 70.0
        tau[2] = (W - B)

    elif t < 55.0:
        # Phase 3: Avoidance turn — M86 log: sway + yaw active
        tau[0] = 40.0         # reduced surge during turn
        tau[1] = 30.0         # sway force Y (N)
        tau[5] = 25.0         # yaw moment N (N·m)
        tau[2] = (W - B)

    else:
        # Phase 4: Resume cruise
        tau[0] = 70.0
        tau[2] = (W - B)

    return tau

