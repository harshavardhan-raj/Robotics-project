def kinetic_energy(nu, M):
    """
    Kinetic Energy:  T = ½ νᵀ M ν

    Includes:
      - Translational KE: ½m(u²+v²+w²)
      - Rotational KE: ½(Ix·p² + Iy·q² + Iz·r²)
      - Added mass KE: ½(|Xu_dot|u² + |Yv_dot|v² + ...)
    """
    T = 0.5 * nu @ M @ nu
    return T

def potential_energy(eta):
    """
    Potential Energy:  U = W·zG - B·zB

    As AUV dives deeper (z increases):
      - Gravitational PE increases (W·z)
      - Work done against/by buoyancy
    """
    z = eta[2]   # current depth from CTD/depth sensor
    U = W * (zg + z) - B * (zb + z)
    return U

