def rotation_matrix_R(phi, theta, psi):
    """Rotation matrix R — same as FK but used here for J⁻¹"""
    cphi = np.cos(phi); sphi = np.sin(phi)
    ctheta = np.cos(theta); stheta = np.sin(theta)
    cpsi = np.cos(psi); spsi = np.sin(psi)

    R = np.array([
        [cpsi*ctheta, cpsi*stheta*sphi - spsi*cphi, cpsi*stheta*cphi + spsi*sphi],
        [spsi*ctheta, spsi*stheta*sphi + cpsi*cphi, spsi*stheta*cphi - cpsi*sphi],
        [-stheta,     ctheta*sphi,                  ctheta*cphi                 ]
    ])
    return R

def J2_inverse(phi, theta):
    """
    J2⁻¹ — Inverse of angular velocity transform

    J2⁻¹ = | 1    0      -sinθ     |
            | 0   cosφ   sinφ·cosθ |
            | 0  -sinφ   cosφ·cosθ |
    """
    cphi = np.cos(phi); sphi = np.sin(phi)
    ctheta = np.cos(theta); stheta = np.sin(theta)

    J2_inv = np.array([
        [1,  0,          -stheta      ],
        [0,  cphi,       sphi*ctheta  ],
        [0, -sphi,       cphi*ctheta  ]
    ])
    return J2_inv

def jacobian_inverse(phi, theta, psi):
    """
    Full 6x6 Inverse Jacobian J(η)⁻¹

    J⁻¹(η) = | Rᵀ     0      |
              |  0   J2⁻¹(η) |

    Since R is orthogonal: R⁻¹ = Rᵀ
    """
    R       = rotation_matrix_R(phi, theta, psi)
    J2_inv  = J2_inverse(phi, theta)

    J_inv = np.zeros((6, 6))
    J_inv[0:3, 0:3] = R.T       # Rᵀ for linear part
    J_inv[3:6, 3:6] = J2_inv    # J2⁻¹ for angular part
    return J_inv

def compute_desired_world_velocity(eta, waypoint, Kp=0.15):
    """
    Compute desired world-frame velocity toward next waypoint

    η̇desired = Kp · (waypoint - eta)

    Proportional guidance law — standard for AUV waypoint tracking
    """
    error = waypoint - eta[0:3]
    dist  = np.linalg.norm(error)

    # Direction unit vector
    if dist > 0.01:
        direction = error / dist
    else:
        direction = np.zeros(3)

    # Scale by proportional gain and saturate
    speed = np.clip(Kp * dist, 0, MAX_SURGE_SPEED)
    eta_dot_desired_pos = direction * speed

    # Desired world-frame velocity (6D: position + orientation rates)
    # Orientation rates = 0 for waypoint tracking (position-only guidance)
    eta_dot_desired = np.zeros(6)
    eta_dot_desired[0:3] = eta_dot_desired_pos
    return eta_dot_desired, dist

def inverse_kinematics(eta, waypoint, Kp=0.15):
    """
    INVERSE KINEMATICS:  ν = J(η)⁻¹ · η̇desired

    Given desired world-frame position (waypoint),
    compute required body-frame velocities ν

    Steps:
      1. Compute η̇desired from guidance law
      2. Compute J⁻¹(η) from current orientation
      3. ν = J⁻¹(η) · η̇desired
      4. Saturate ν to physical limits (from URDF)
    """
    phi, theta, psi = eta[3], eta[4], eta[5]

    # Step 1: Desired world-frame velocity
    eta_dot_desired, dist = compute_desired_world_velocity(eta, waypoint, Kp)

    # Step 2: Inverse Jacobian
    J_inv = jacobian_inverse(phi, theta, psi)

    # Step 3: INVERSE KINEMATICS EQUATION
    nu_desired = J_inv @ eta_dot_desired   # ν = J⁻¹(η) · η̇d

    # Step 4: Saturate to physical limits (autosub6000.urdf)
    nu_desired[0] = np.clip(nu_desired[0], -MAX_SURGE_SPEED, MAX_SURGE_SPEED)
    nu_desired[1] = np.clip(nu_desired[1], -MAX_SWAY_SPEED,  MAX_SWAY_SPEED)
    nu_desired[2] = np.clip(nu_desired[2], -MAX_HEAVE_SPEED, MAX_HEAVE_SPEED)
    nu_desired[5] = np.clip(nu_desired[5], -MAX_YAW_RATE,    MAX_YAW_RATE)

    return nu_desired, eta_dot_desired, J_inv, dist

